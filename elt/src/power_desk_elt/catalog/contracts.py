"""Export ODCS data contracts for the queryable relations (`marts`, `ods`, `dims`, dimension seeds `dim_*`).

    uv run python -m power_desk_elt.catalog.contracts [--check]

One contract per relation, in Open Data Contract Standard v3.2.0, written to `elt/contracts/<schema>/`.
Nothing in a contract is written by hand; it is exported from:
- the dbt manifest (`dbt parse` or `dbt build`): descriptions, and the data tests that verify the contract,
  as its keys, required columns, relationships and quality rules
- dbt `meta`: query guidance as ODCS `context`, a folder's `layer_context` (dbt_project.yml) followed by the
  model's own `context`, each with `instructions` and `constraints`
- `catalog/definitions`: the official sources of each definition, as `authoritativeDefinitions`
- the warehouse: column types and order, and the units of the measures (`dims.dim_metric`)

`--check` exits non-zero if any contract is stale.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
from typing import Any

import duckdb
import yaml

from power_desk_elt.catalog.definitions_loader import load_definitions, load_snapshots
from power_desk_elt.catalog.render import Catalogue
from power_desk_elt.settings import DBT_PROJECT_DIR, ELT_ROOT, dbt_manifest_path
import power_desk_warehouse as warehouse

CONTRACTS_DIR = ELT_ROOT / "contracts"
ODCS_VERSION = "v3.2.0"
SCHEMAS = ("marts", "ods", "dims")
HEADER = "# GENERATED by `python -m power_desk_elt.catalog.contracts` from the dbt project - do not edit.\n"
# DuckDB type (unsigned integers without their `U`) -> ODCS logical type
LOGICAL_TYPES = {
    "TIMESTAMP": "timestamp",
    "DATE": "date",
    "TIME": "time",
    "BOOLEAN": "boolean",
    "VARCHAR": "string",
    "DOUBLE": "number",
    "FLOAT": "number",
    "DECIMAL": "number",
    "TINYINT": "integer",
    "SMALLINT": "integer",
    "INTEGER": "integer",
    "BIGINT": "integer",
    "HUGEINT": "integer",
    "STRUCT": "object",
    "MAP": "map",
}
# unit by column suffix (docs/architecture.md, Naming), for measures not in dim_metric
SUFFIX_UNITS = {"_mw": "MW", "_mwh": "MWh", "_pct": "percent"}
QUALITY_DIMENSIONS = {
    "not_null": "completeness",
    "no_missing_intervals": "completeness",
    "no_missing_settlement_periods": "completeness",
    "unique": "uniqueness",
    "dlt_unique": "uniqueness",
    "relationships": "conformity",
    "accepted_values": "conformity",
    "expression_is_true": "consistency",
}
DOC_REF = re.compile(r"doc\('(?:col|dataset)_(\w+)'\)")


class _NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data: Any) -> bool:
        return True


def logical_type(physical_type: str) -> str | None:
    if physical_type.endswith("[]"):
        return "array"
    base = re.split(r"[ (]", physical_type, maxsplit=1)[0]
    return LOGICAL_TYPES.get(base) or LOGICAL_TYPES.get(base.removeprefix("U"))


def warehouse_columns(con: duckdb.DuckDBPyConnection) -> dict[tuple[str, str], list[tuple[str, str]]]:
    """{(schema, relation): [(column, type)]}, in column order."""
    rows = con.execute(
        f"""
        select table_schema, table_name, column_name, data_type from information_schema.columns
        where table_schema in ({", ".join("?" for _ in SCHEMAS)}) order by table_schema, table_name, ordinal_position
        """,
        list(SCHEMAS),
    ).fetchall()
    columns: dict[tuple[str, str], list[tuple[str, str]]] = {}
    for schema, table, column, data_type in rows:
        columns.setdefault((schema, table), []).append((column, data_type))
    return columns


def units(con: duckdb.DuckDBPyConnection) -> dict[str, dict[str, str]]:
    """{metric: {unit, hourlyAggregation}} from `dims.dim_metric`."""
    rows = con.execute("select metric, unit, hourly_aggregation from dims.dim_metric").fetchall()
    return {metric: {"unit": unit, "hourlyAggregation": aggregation} for metric, unit, aggregation in rows}


def raw_descriptions(node: dict[str, Any]) -> tuple[str, dict[str, str]]:
    """The model's and its columns' descriptions as written (with their `{{ doc() }}` references)."""
    path = DBT_PROJECT_DIR / node["patch_path"].partition("://")[2]
    section = "seeds" if node["resource_type"] == "seed" else "models"
    models = (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get(section, [])
    model = next(m for m in models if m["name"] == node["name"])
    return model.get("description", ""), {c["name"]: c.get("description", "") for c in model.get("columns", [])}


def authoritative_definitions(catalogue: Catalogue, raw: str, section: str) -> list[dict[str, str]]:
    """Official sources of the definitions a description references (`col_<key>`, `dataset_<table>`)."""
    out = []
    for key in DOC_REF.findall(raw):
        entry = getattr(catalogue, section).get(key)
        for ref in catalogue.references(entry) if entry else []:
            where = ", ".join(str(ref[k]) for k in ("section", "page", "path") if k in ref)
            description = f"{ref['title']} ({where})" if where else ref["title"]
            item = {"url": ref["url"], "type": "businessDefinition", "description": description}
            if item not in out:
                out.append(item)
    return out


def test_rule(test: dict[str, Any], nodes: dict[str, Any]) -> tuple[str, str]:
    """(kind, readable rule) of a dbt data test."""
    meta = test.get("test_metadata") or {}
    kind, kwargs = meta.get("name", "singular"), meta.get("kwargs", {})
    if kind == "relationships":
        return kind, f"every value is a key of {relationship_target(test, nodes)}"
    if kind == "dlt_unique":
        return kind, f"unique on ({', '.join(kwargs['columns'])})"
    if kind == "expression_is_true":
        return kind, f"every row satisfies `{kwargs['expression']}`"
    if kind == "accepted_values":
        return kind, f"one of {', '.join(map(str, kwargs['values']))}"
    if kind == "not_null":
        return kind, "not null"
    return kind, test.get("description") or kind.replace("_", " ")


def relationship_target(test: dict[str, Any], nodes: dict[str, Any]) -> str:
    """`relation.column` a relationships test points at (shorthand reference)."""
    # the other node, or the attached node itself for a relationship within one relation (a parent key)
    target = next((n for n in test["depends_on"]["nodes"] if n != test["attached_node"]), test["attached_node"])
    return f"{nodes[target]['name']}.{test['test_metadata']['kwargs']['field']}"


def quality(test: dict[str, Any], nodes: dict[str, Any]) -> dict[str, Any]:
    kind, rule = test_rule(test, nodes)
    return {
        "name": test["name"],
        "description": rule,
        "type": "custom",
        "engine": "dbt",
        "implementation": test["name"],
        **({"dimension": QUALITY_DIMENSIONS[kind]} if kind in QUALITY_DIMENSIONS else {}),
        "severity": "warning" if test["config"]["severity"].lower() == "warn" else "error",
    }


def grain(tests: list[dict[str, Any]]) -> list[str]:
    """Columns of the model's uniqueness test (its grain), the `*_unique_key` one where there are several."""
    keys = [t for t in tests if (t.get("test_metadata") or {}).get("name") == "dlt_unique" and not t.get("column_name")]
    keys.sort(key=lambda t: not t["name"].endswith("_unique_key"))
    return keys[0]["test_metadata"]["kwargs"]["columns"] if keys else []


def context(meta: dict[str, Any]) -> dict[str, Any]:
    """ODCS `context`: the folder's `layer_context`, then the model's own `context`."""
    parts = [meta.get("layer_context") or {}, meta.get("context") or {}]
    instructions = "\n\n".join(p["instructions"].strip() for p in parts if p.get("instructions"))
    constraints = [{"constraint": c} for p in parts for c in p.get("constraints", [])]
    return {
        **({"instructions": instructions} if instructions else {}),
        **({"constraints": constraints} if constraints else {}),
    }


def schema_property(
    name: str,
    physical_type: str,
    node: dict[str, Any],
    tests: list[dict[str, Any]],
    key: list[str],
    raw: str,
    nodes: dict[str, Any],
    catalogue: Catalogue,
    metrics: dict[str, dict[str, str]],
) -> dict[str, Any]:
    column_tests = [t for t in tests if t.get("column_name") == name]
    kinds = {(t["test_metadata"]["name"], t["config"]["severity"].lower()) for t in column_tests}
    relationships = [
        {"to": relationship_target(t, nodes)} for t in column_tests if t["test_metadata"]["name"] == "relationships"
    ]
    unit = metrics.get(name) or next(({"unit": u} for s, u in SUFFIX_UNITS.items() if name.endswith(s)), {})
    custom = [{"property": k, "value": v} for k, v in unit.items()]
    definitions = authoritative_definitions(catalogue, raw, "columns")
    description = node["columns"].get(name, {}).get("description", "").strip()
    return {
        "name": name,
        **({"logicalType": logical_type(physical_type)} if logical_type(physical_type) else {}),
        "physicalType": physical_type,
        **({"description": description} if description else {}),
        **({"primaryKey": True, "primaryKeyPosition": key.index(name) + 1} if name in key else {}),
        **({"required": True} if ("not_null", "error") in kinds else {}),
        **({"unique": True} if {("unique", "error"), ("dlt_unique", "error")} & kinds else {}),
        **({"relationships": relationships} if relationships else {}),
        **({"authoritativeDefinitions": definitions} if definitions else {}),
        **({"customProperties": custom} if custom else {}),
        **({"quality": [quality(t, nodes) for t in column_tests]} if column_tests else {}),
    }


def contract(
    node: dict[str, Any],
    columns: list[tuple[str, str]],
    tests: list[dict[str, Any]],
    nodes: dict[str, Any],
    catalogue: Catalogue,
    metrics: dict[str, dict[str, str]],
    version: str,
) -> dict[str, Any]:
    schema, name = node["schema"], node["alias"] or node["name"]
    raw_description, raw_columns = raw_descriptions(node)
    key = grain(tests)
    ctx = context(node["config"].get("meta") or {})
    definitions = authoritative_definitions(catalogue, raw_description, "tables")
    return {
        "apiVersion": ODCS_VERSION,
        "kind": "DataContract",
        "id": f"power_desk.{schema}.{name}",
        "name": name,
        "version": version,
        "status": "active",
        "domain": schema,
        "servers": [
            {
                "server": env,
                "type": "duckdb",
                "environment": env,
                "database": f"data/warehouse_{env}.duckdb",
                "schema": schema,
            }
            for env in ("prod", "dev")
        ],
        "schema": [
            {
                "name": name,
                "physicalName": name,
                "physicalType": "view" if node["config"]["materialized"] == "view" else "table",
                "logicalType": "object",
                "description": node["description"].strip(),
                **({"dataGranularityDescription": f"One row per {', '.join(key)}."} if key else {}),
                **({"authoritativeDefinitions": definitions} if definitions else {}),
                **({"context": ctx} if ctx else {}),
                "properties": [
                    schema_property(
                        column, physical_type, node, tests, key, raw_columns.get(column, ""), nodes, catalogue, metrics
                    )
                    for column, physical_type in columns
                ],
                **(
                    {"quality": [quality(t, nodes) for t in tests if not t.get("column_name")]}
                    if any(not t.get("column_name") for t in tests)
                    else {}
                ),
            }
        ],
    }


def export(manifest: dict[str, Any], db_path: Path | str | None = None) -> dict[Path, str]:
    """{path: contract YAML} for every model in `SCHEMAS`, and every seed that is a dimension (`dim_*`)."""
    nodes = manifest["nodes"]
    catalogue = Catalogue(load_definitions(), load_snapshots())
    version = yaml.safe_load((DBT_PROJECT_DIR / "dbt_project.yml").read_text(encoding="utf-8"))["version"]
    tests: dict[str, list[dict[str, Any]]] = {}
    for test in sorted((n for n in nodes.values() if n["resource_type"] == "test"), key=lambda t: t["name"]):
        if test.get("attached_node"):
            tests.setdefault(test["attached_node"], []).append(test)
    with warehouse.connect(db_path) as con:
        columns, metrics = warehouse_columns(con), units(con)
    outputs = {}
    for unique_id, node in sorted(nodes.items()):
        name = node["alias"] or node["name"]
        dimension_seed = node["resource_type"] == "seed" and name.startswith("dim_")
        if not (node["resource_type"] == "model" or dimension_seed) or node["schema"] not in SCHEMAS:
            continue
        doc = contract(
            node, columns[node["schema"], name], tests.get(unique_id, []), nodes, catalogue, metrics, version
        )
        text = HEADER + yaml.dump(doc, Dumper=_NoAliasDumper, sort_keys=False, width=120, allow_unicode=True)
        outputs[CONTRACTS_DIR / node["schema"] / f"{name}.odcs.yaml"] = text
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").partition("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if contracts are out of date")
    args = parser.parse_args()

    path = dbt_manifest_path()
    if not path.exists():
        print(f"no dbt manifest at {path}; run `dbt parse` or `dbt build` first", file=sys.stderr)
        return 1
    outputs = export(json.loads(path.read_text(encoding="utf-8")))
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    orphans = sorted(set(CONTRACTS_DIR.glob("*/*.odcs.yaml")) - set(outputs))
    if args.check:
        for p in [*stale, *orphans]:
            print(f"out of date: {p}", file=sys.stderr)
        return 1 if stale or orphans else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p], encoding="utf-8")
        print(f"wrote {p}")
    for p in orphans:
        p.unlink()
        print(f"removed {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
