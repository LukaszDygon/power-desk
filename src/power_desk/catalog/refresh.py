"""Refresh provider snapshots for every reference used in `catalog/definitions/`.

    uv run python -m power_desk.catalog.refresh [--provider <name>]

Snapshots (`catalog/snapshots/<provider>.yml`) are committed: docs build offline, and a
refresh shows up as a reviewable diff. Run `python -m power_desk.catalog.generate` after.
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from datetime import UTC, datetime

import yaml

from power_desk.catalog.definitions_loader import SNAPSHOTS_DIR, load_definitions, referenced
from power_desk.catalog.providers import PROVIDERS, parse_ref


def main() -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").partition("\n")[0])
    parser.add_argument("--provider", choices=sorted(PROVIDERS), help="only refresh this provider")
    args = parser.parse_args()

    wanted: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for ref in referenced(load_definitions()):
        provider, kind, ident = parse_ref(ref)
        wanted[provider][kind].append(ident)

    SNAPSHOTS_DIR.mkdir(exist_ok=True)
    for provider, kinds in sorted(wanted.items()):
        if args.provider and provider != args.provider:
            continue
        module = PROVIDERS[provider]
        entries = {
            f"{kind}/{ident}": entry
            for kind, ids in sorted(kinds.items())
            for ident, entry in module.fetch(kind, ids).items()
        }
        snapshot = {"retrieved": datetime.now(UTC).date().isoformat(), "entries": entries}
        path = SNAPSHOTS_DIR / f"{provider}.yml"
        header = (
            f"# GENERATED by `python -m power_desk.catalog.refresh` - {provider} definitions snapshot, do not edit.\n"
        )
        path.write_text(header + yaml.safe_dump(snapshot, sort_keys=False, allow_unicode=True, width=100))
        print(f"wrote {path} ({len(entries)} entries)")


if __name__ == "__main__":
    main()
