"""Definitions rendered for dbt: doc blocks with the definition text, `meta.references` with its origin."""

from __future__ import annotations

from typing import Any

from power_desk.catalog import CatalogError
from power_desk.catalog.providers import PROVIDERS, parse_ref


def dataset_doc(table: str) -> str:
    """Name of a table's doc block."""
    return f"dataset_{table}"


class Catalogue:
    """Resolves definition keys and provider references into markdown doc blocks."""

    def __init__(self, definitions: dict[str, Any], snapshots: dict[str, Any]) -> None:
        self.definitions = definitions
        self.snapshots = snapshots
        self.tables: dict[str, Any] = definitions["tables"]
        self.columns: dict[str, Any] = definitions["columns"]

    def column_key(self, table: str, column: str) -> str:
        key = self.tables.get(table, {}).get("columns", {}).get(column, column)
        if key not in self.columns:
            raise CatalogError(f"{table}.{column}: no definition `{key}` in catalog/definitions (columns:)")
        return key

    def resolve(self, ref: str) -> tuple[str, dict[str, Any], str]:
        provider, kind, ident = parse_ref(ref)
        snapshot = self.snapshots.get(provider, {})
        try:
            entry = snapshot["entries"][f"{kind}/{ident}"]
        except KeyError:
            raise CatalogError(
                f"{ref} missing from snapshots/{provider}.yml; run `python -m power_desk.catalog.refresh`"
            ) from None
        return PROVIDERS[provider].LABELS.get(kind, f"{provider} {kind}"), entry, snapshot["retrieved"]

    def text(self, entry: dict[str, Any]) -> str:
        """The definition: the local description, else the publisher's wording of its references."""
        if entry.get("description"):
            return entry["description"].strip()
        parts = []
        for ref in entry.get("refs", []):
            _, item, _ = self.resolve(ref)
            parts += [item.get("summary", ""), item.get("definition", "")]
        return "\n\n".join(p.strip() for p in parts if p)

    def references(self, entry: dict[str, Any]) -> list[dict[str, Any]]:
        """Where a definition comes from, for `meta.references`: provider entries, then documents."""
        out = []
        for ref in entry.get("refs", []):
            label, item, retrieved = self.resolve(ref)
            out.append(
                {
                    "title": f"{label}: {item['title']}",
                    "url": item["url"],
                    "id": ref,
                    "retrieved": retrieved,
                    **({"detail": item["reference"]} if item.get("reference") else {}),
                }
            )
        if entry.get("url"):
            out.append({"title": entry.get("title") or "Publication", "url": entry["url"]})
        for link in entry.get("links", []):
            spec = link if isinstance(link, dict) else {"link": link}
            document = self.definitions["links"][spec["link"]]
            out.append(
                {
                    "title": document["title"],
                    "url": document["url"],
                    **{k: spec[k] for k in ("section", "page", "path") if k in spec},
                }
            )
        return out

    def dataset_md(self, table: str) -> str:
        entry = self.tables[table]
        title = entry.get("title") or next((self.resolve(r)[1]["title"] for r in entry.get("refs", [])), "")
        return "\n\n".join(p for p in (f"**{title}**" if title else "", self.text(entry)) if p)

    def column_md(self, key: str) -> str:
        return self.text(self.columns[key])

    def docs_file(self) -> str:
        out = [
            "{# GENERATED by `python -m power_desk.catalog.generate` from catalog/definitions and "
            "catalog/snapshots - do not edit. #}",
        ]
        for table in self.tables:
            out.append(f"{{% docs {dataset_doc(table)} %}}\n{self.dataset_md(table)}\n{{% enddocs %}}")
        for key in self.columns:
            out.append(f"{{% docs col_{key} %}}\n{self.column_md(key)}\n{{% enddocs %}}")
        return "\n\n".join(out) + "\n"
