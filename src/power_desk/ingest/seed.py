"""Seed generator and loader for Power Desk.

Generates a realistic 7-day UK power system dataset shaped exactly like the raw
API payloads (camelCase BMRS records, PVLive rows), so loading it through dlt
produces the same `raw` tables as the live pipelines:

- FUELINST at 5-minute ticks per fuel type
- INDO / ITSDO / NDF per settlement period
- WINDFOR hourly
- PVLive half-hourly (half-hour ending)
"""

from __future__ import annotations

from datetime import UTC, date, datetime, timedelta
import json
import math
from pathlib import Path
import random
from typing import Any
from zoneinfo import ZoneInfo

import dlt
import duckdb

from power_desk.ingest.bmrs import get_default_builder
from power_desk.ingest.entsoe_eic import SCD2
from power_desk.ingest.pipelines import make_pipeline

SEED_DIR = Path(__file__).resolve().parents[3] / "data" / "seed"
LONDON = ZoneInfo("Europe/London")

SEED_TABLES = ("raw_fuelinst", "raw_indo", "raw_itsdo", "raw_demand_forecast", "raw_windfor", "raw_pvlive_solar")
PVLIVE_PRIMARY_KEY = ["pes_id", "datetime_gmt"]
# Reference snapshots: a small real extract of the ENTSO-E EIC files (codes the curated
# mappings reference, a few unit hierarchies, all functions and issuing offices). Not
# regenerated by `generate_seed_data`; loaded with scd2 like the live `entsoe_eic` source.
REFERENCE_TABLES = ("raw_eic_codes", "raw_eic_functions", "raw_eic_issuing_offices")


def iso(ts: datetime) -> str:
    return ts.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def settlement_periods(day: date) -> list[tuple[int, datetime]]:
    """(period, UTC start) for every settlement period of a UK settlement day (46/48/50)."""
    start = datetime(day.year, day.month, day.day, tzinfo=LONDON).astimezone(UTC)
    nxt = day + timedelta(days=1)
    end = datetime(nxt.year, nxt.month, nxt.day, tzinfo=LONDON).astimezone(UTC)
    count = int((end - start).total_seconds() // 1800)
    return [(p, start + timedelta(minutes=30 * (p - 1))) for p in range(1, count + 1)]


def generate_seed_data(
    start_date: str = "2024-03-01",
    num_days: int = 7,
    output_dir: Path | str | None = None,
) -> dict[str, int]:
    """Generate realistic raw BMRS + PVLive parquet datasets."""
    out_path = Path(output_dir or SEED_DIR)
    out_path.mkdir(parents=True, exist_ok=True)
    random.seed(42)

    records: dict[str, list[dict[str, Any]]] = {name: [] for name in SEED_TABLES}
    start_d = date.fromisoformat(start_date)

    for d_idx in range(num_days):
        day = start_d + timedelta(days=d_idx)
        daily_wind_base = 5000 + 7000 * math.sin(d_idx * 0.8)

        for period, period_start in settlement_periods(day):
            hour = (period - 1) * 0.5
            common = {"settlementDate": day.isoformat(), "settlementPeriod": period}

            demand_curve = (
                22000
                + 12000 * math.sin((hour - 4) / 24.0 * math.pi) ** 2
                + 4000 * math.exp(-((hour - 18) ** 2) / 8.0)
            )
            actual_demand = round(demand_curve + random.gauss(0, 400))
            forecast_demand = round(demand_curve + random.gauss(0, 750))

            solar_factor = max(0.0, math.sin((hour - 6) / 14.0 * math.pi)) if 6 <= hour <= 20 else 0.0
            solar_gen = round(solar_factor * 6500 + random.uniform(0, 200)) if solar_factor > 0 else 0
            wind_gen = round(max(800, daily_wind_base + 2500 * math.sin(hour / 4.0) + random.gauss(0, 300)))
            nuclear_gen = round(4200 + random.gauss(0, 50))
            biomass_gen = round(2100 + random.gauss(0, 40))
            hydro_gen = round(350 + (400 if 17 <= hour <= 20 else 50))
            intfr_gen = round(1500 + 300 * math.sin(hour))
            intned_gen = round(800 + 200 * math.cos(hour))
            clean = solar_gen + wind_gen + nuclear_gen + biomass_gen + hydro_gen + intfr_gen + intned_gen
            gas_gen = round(max(1500, actual_demand - clean) + random.gauss(0, 150))

            fuel_map = {
                "CCGT": gas_gen,
                "OCGT": 0,
                "OIL": 0,
                "COAL": 0,
                "NUCLEAR": nuclear_gen,
                "WIND": wind_gen,
                "PS": 50,
                "NPSHYD": hydro_gen,
                "OTHER": 120,
                "BIOMASS": biomass_gen,
                "INTFR": intfr_gen,
                "INTNED": intned_gen,
            }
            for tick in range(6):
                tick_start = period_start + timedelta(minutes=5 * tick)
                for fuel, gen in fuel_map.items():
                    records["raw_fuelinst"].append({
                        "dataset": "FUELINST",
                        "publishTime": iso(tick_start + timedelta(minutes=5)),
                        "startTime": iso(tick_start),
                        **common,
                        "fuelType": fuel,
                        "generation": max(0, gen + (round(random.gauss(0, 25)) if gen else 0)),
                    })

            publish = iso(period_start + timedelta(minutes=30))
            records["raw_indo"].append({
                "dataset": "INDO", "publishTime": publish, "startTime": iso(period_start), **common,
                "demand": actual_demand,
            })
            records["raw_itsdo"].append({
                "dataset": "ITSDO", "publishTime": publish, "startTime": iso(period_start), **common,
                "demand": actual_demand + 1200,
            })
            records["raw_demand_forecast"].append({
                "dataset": "NDF", "demand": forecast_demand,
                "publishTime": iso(period_start - timedelta(hours=12)), "startTime": iso(period_start),
                **common, "boundary": "N",
            })
            if period_start.minute == 0:
                records["raw_windfor"].append({
                    "dataset": "WINDFOR",
                    "publishTime": iso(period_start - timedelta(hours=12)),
                    "startTime": iso(period_start),
                    "generation": round(max(800, wind_gen + random.gauss(0, 600))),
                })
            records["raw_pvlive_solar"].append({
                "pes_id": 0,
                "datetime_gmt": iso(period_start + timedelta(minutes=30)),
                "generation_mw": float(solar_gen),
            })

    con = duckdb.connect()
    for name, rows in records.items():
        tmp_json = out_path / f".{name}.json"
        tmp_json.write_text(json.dumps(rows), encoding="utf-8")
        # Keep every field as its JSON type (no timestamp sniffing), like the API payload.
        con.execute(
            f"COPY (SELECT * FROM read_json('{tmp_json.as_posix()}', format='array', "
            f"timestampformat='NONE', dateformat='NONE')) "
            f"TO '{(out_path / f'{name}.parquet').as_posix()}' (FORMAT PARQUET)"
        )
        tmp_json.unlink()
    con.close()
    return {name: len(rows) for name, rows in records.items()}


def _seed_resources(seed_dir: Path) -> list[Any]:
    primary_keys = {name: cfg.primary_key for name, cfg in get_default_builder().configs.items()}
    primary_keys["raw_pvlive_solar"] = PVLIVE_PRIMARY_KEY
    resources = []
    for name in (*SEED_TABLES, *REFERENCE_TABLES):
        path = seed_dir / f"{name}.parquet"
        if not path.exists():
            continue

        def rows(path: Path = path) -> Any:
            con = duckdb.connect()
            cur = con.execute(f"SELECT * FROM read_parquet('{path.as_posix()}')")
            cols = [d[0] for d in cur.description]
            yield [dict(zip(cols, r)) for r in cur.fetchall()]
            con.close()

        if name in REFERENCE_TABLES:
            resources.append(dlt.resource(rows, name=name, write_disposition=SCD2))
        else:
            resources.append(dlt.resource(rows, name=name, write_disposition="merge", primary_key=primary_keys[name]))
    return resources


def load_seed(db_path: Path | str | None = None, seed_dir: Path | str | None = None) -> Any:
    """Load the seed parquet files into `raw` through dlt (pipeline `seed`)."""
    pipeline = make_pipeline("seed", db_path=db_path, export_schema=False)
    return pipeline.run(_seed_resources(Path(seed_dir or SEED_DIR)))


if __name__ == "__main__":
    print("Seed parquet files generated successfully:", generate_seed_data())
